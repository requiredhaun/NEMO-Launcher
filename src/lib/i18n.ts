import { useSyncExternalStore } from 'react'

export type Lang = 'ru' | 'en'

const LS_KEY = 'nemo-lang'

function readStored(): Lang {
  try {
    return window.localStorage.getItem(LS_KEY) === 'en' ? 'en' : 'ru'
  } catch {
    return 'ru'
  }
}

let cur: Lang = typeof window === 'undefined' ? 'ru' : readStored()
const subs = new Set<() => void>()

export function getLang(): Lang {
  return cur
}

export function setLang(l: Lang): void {
  if (l !== 'ru' && l !== 'en') return
  if (cur === l) return
  cur = l
  try {
    window.localStorage.setItem(LS_KEY, l)
  } catch { /* ignore */ }
  subs.forEach((fn) => fn())
}

function subscribe(fn: () => void): () => void {
  subs.add(fn)
  return () => {
    subs.delete(fn)
  }
}

/** Подписка на язык: перерисовывает компонент при смене языка. */
export function useLang(): Lang {
  return useSyncExternalStore(subscribe, () => cur, () => cur)
}

